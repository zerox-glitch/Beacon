type ArtDirectionSpec = Omit<
  ArtDirection,
  "strength" | "accentFreq" | "quietZone" | "alignment" | "minSeparation"
> &
  Partial<Pick<ArtDirection, "strength" | "accentFreq" | "quietZone" | "alignment" | "minSeparation">>;

function d(spec: ArtDirectionSpec): ArtDirection {
  return {
    ...spec,
    strength: spec.strength ?? 0.6,
    accentFreq: spec.accentFreq ?? 0,
    quietZone: spec.quietZone ?? 3,
    alignment: spec.alignment ?? "solid",
    minSeparation: spec.minSeparation ?? MIN_SEPARATION,
    lod: {
      // Camera-safe simplification ladder, per direction unless overridden.
      lean: {
        geometry: spec.geometry === "traces" ? "runs-both" : spec.geometry,
        distortion: "none",
        accent: "none",
        gap: Math.min(spec.gap, 0.03),
        mass: Math.max(spec.mass, 0.88),
        contrastBoost: 0.04,
        ...(spec.lod?.lean ?? {}),
      },
      standard: {
        distortion: spec.distortion === "jitter" ? "none" : spec.distortion,
        ...(spec.lod?.standard ?? {}),
      },
    },
    cameraSafe: {
      geometry: "single",
      distortion: "none",
      accent: "none",
      gradient: spec.gradient === "bands" || spec.gradient === "spectrum" ? "linear-y" : spec.gradient,
      shape:
        coverageOf(spec.shape) < 0.6
          ? "rounded"
          : spec.shape === "hbar" || spec.shape === "vbar"
            ? "rounded"
            : spec.shape,
      radius: Math.min(spec.radius, 0.34),
      gap: 0,
      mass: 0.95,
      contrastBoost: 0.06,
      ...(spec.cameraSafe ?? {}),
    },
  };
}


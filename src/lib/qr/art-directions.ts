/**
 * ART QR STYLE SYSTEM — the 50 art directions.
 *
 * Global rules this file is responsible for:
 *
 *   1. QR structural integrity — directions never touch the matrix, they only
 *      describe how it is painted (see art-plan.ts).
 *   2. Camera scanability — every direction ships a `cameraSafe` fallback and
 *      per-level-of-detail tweaks driven by pixelsPerModule.
 *   3. Finder-pattern detection — finder styles keep the 1:1:3:1:1 ratio.
 *   4. Quiet-zone preservation — `quietZone >= 3` and the plan clips to the body.
 *   5. Aggregate dark/light separation — `resolveInks` measures *luminance*,
 *      never assumes "red vs blue = contrast", and repairs any ramp that fails.
 *   6. Visual beauty — each direction varies shape + geometry + distortion +
 *      gradient + finder + accent, so the gallery reads as 50 design systems
 *      rather than 50 colour swaps.
 */


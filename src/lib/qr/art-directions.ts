export const TEMPLATE_CATEGORY = "Templates";

const inkCache = new Map<string, ResolvedInks>();

/**
 * Cached, gate-checked inks for a direction. Keyed on the required separation
 * too, because the relax ladder raises `minSeparation` — a rung that asks for
 * more contrast must actually get more contrast.
 */
export function inksFor(dir: ArtDirection): ResolvedInks {
  // Keyed on every colour-bearing field, not just the id: relax rungs and QA
  // probes clone directions with patched palettes, and a stale cache entry
  // would silently render the OLD colours (this exact bug invalidated a whole
  // round of tuning measurements before it was caught).
  const key = [
    dir.id,
    (dir.minSeparation ?? MIN_SEPARATION).toFixed(3),
    dir.bg,
    dir.stops.join(","),
    (dir.ramp ?? []).join(","),
    dir.eye ?? "",
    dir.ball ?? "",
    dir.accent ?? "",
  ].join("|");
  const hit = inkCache.get(key);
  if (hit) return hit;
  const resolved = resolveInks(dir);
  inkCache.set(key, resolved);
  return resolved;
}

/** Directions whose colour gate had to repair something — surfaced in QA. */
export function inkRepairReport(): { id: string; name: string; repairs: string[]; separation: number }[] {
  return ART_DIRECTIONS.map((dir) => {
    const inks = inksFor(dir);
    return { id: dir.id, name: dir.name, repairs: inks.repairs, separation: inks.separation };
  }).filter((row) => row.repairs.length > 0);
}

/**
 * Every direction as a studio preset. Same underlying QR matrix as everything
 * else — a direction is paint, never a different encoding.
 */
export function artDirectionPresets(): Preset[] {
  return ART_DIRECTIONS.map((dir) => {
    const inks = inksFor(dir);
    const style: QrStyle = {
      ...DEFAULT_STYLE,
      moduleShape: "square",
      eyeShape: "square",
      ballShape: "square",
      fg: inks.stops[0]!,
      bg: inks.bg,
      eyeColor: inks.eye,
      ballColor: inks.ball,
      gradientType: "none",
      gradientTo: inks.stops[inks.stops.length - 1]!,
      quietZone: Math.max(3, dir.quietZone),
      moduleGap: dir.gap,
      // Template kits reserve the centre plate for an uploaded brand mark;
      // art directions stay image-free so the artwork carries the design.
      imageMode: dir.category === "Templates" ? "logo" : "none",
      logoScale: dir.category === "Templates" ? 0.24 : DEFAULT_STYLE.logoScale,
      dotScale: 0.9,
      contrast: 0.9,
      minVersion: 5,
      ecc: "Q",
      artisticStrength: dir.strength,
      effect: "none",
      maskPattern: -1,
      artDirection: dir.id,
    };
    return {
      id: `art-${dir.id}`,
      name: dir.name,
      category: dir.category === "Templates" ? TEMPLATE_CATEGORY : ART_DIRECTION_CATEGORY,
      blurb: dir.blurb,
      style,
    };
  });
}
